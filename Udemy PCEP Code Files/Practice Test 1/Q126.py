"""
Erklärung
0o ist das Präfix in Python, das eine Oktalzahl (Basis 8) kennzeichnet.
10 ist also nicht „zehn“ im Dezimalsystem, sondern 1×8¹ + 0×8⁰ = 8 im Dezimalsystem.

| Schreibweise | Basis | Präfix | Beispiel | Dezimalwert |
| ------------ | ----- | ------ | -------- | ----------- |
| Dezimal      | 10    | -      | `10`     | 10          |
| Binär        | 2     | `0b`   | `0b10`   | 2           |
| Oktal        | 8     | `0o`   | `0o10`   | 8           |
| Hexadezimal  | 16    | `0x`   | `0x10`   | 16          |

"""


print(0o10)  # 8 bedeutet, dass 0o10 eine Zahl im Oktalsystem ist.
print(0o77)  # 63
